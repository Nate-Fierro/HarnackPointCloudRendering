"""Create oriented point OBJ fixtures; Stanford bunny input is cached locally."""
import argparse
import bisect
import hashlib
import math
from pathlib import Path
import random
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
BUNNY_URL = "https://graphics.stanford.edu/pub/3Dscanrep/bunny.tar.gz"


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def cross(a, b):
    return (a[1]*b[2] - a[2]*b[1], a[2]*b[0] - a[0]*b[2], a[0]*b[1] - a[1]*b[0])


def unit(v):
    length = math.sqrt(sum(x*x for x in v))
    return tuple(x / length for x in v)


def write_obj(path, points, normals, description):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="ascii", newline="\n") as output:
        output.write(f"# {description}\n# Oriented point cloud: one vn per v in matching order; no faces.\n")
        for tag, values in (("v", points), ("vn", normals)):
            for v in values:
                output.write(f"{tag} {v[0]:.9g} {v[1]:.9g} {v[2]:.9g}\n")
    print(f"Wrote {path}: {len(points)} oriented points")


def sphere(count=1024):
    points = []
    golden_angle = math.pi * (3 - math.sqrt(5))
    for i in range(count):
        y = 1 - 2 * (i + 0.5) / count
        radius = math.sqrt(1 - y*y)
        points.append((radius * math.cos(i * golden_angle), y, radius * math.sin(i * golden_angle)))
    write_obj(ROOT / "data/sphere-points.obj", points, points, "Unit Fibonacci sphere, analytic outward normals; generated by prepare_samples.py")


def bunny(count):
    archive = ROOT / "data/downloads/bunny.tar.gz"
    archive.parent.mkdir(parents=True, exist_ok=True)
    if not archive.exists():
        print(f"Downloading {BUNNY_URL}", flush=True)
        with urllib.request.urlopen(BUNNY_URL, timeout=60) as response:
            archive.write_bytes(response.read())
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    # Read just the named mesh; never extract paths supplied by the archive.
    with tarfile.open(archive, "r:gz") as tar:
        stream = tar.extractfile("bunny/reconstruction/bun_zipper.ply")
        if stream is None:
            raise ValueError("Bunny archive does not contain bun_zipper.ply")
        lines = iter(stream.read().decode("ascii").splitlines())
    vertex_count = face_count = 0
    for line in lines:
        if line.startswith("element vertex "): vertex_count = int(line.split()[2])
        if line.startswith("element face "): face_count = int(line.split()[2])
        if line == "end_header": break
    vertices = [tuple(map(float, next(lines).split()[:3])) for _ in range(vertex_count)]
    normals = [[0., 0., 0.] for _ in vertices]
    faces, weights = [], []
    total = 0.
    for _ in range(face_count):
        fields = list(map(int, next(lines).split()))
        if fields[0] != 3: raise ValueError("Expected a triangular PLY mesh")
        tri = fields[1:4]
        a, b, c = (vertices[j] for j in tri)
        n = cross(sub(b, a), sub(c, a))
        area = 0.5 * math.sqrt(sum(x*x for x in n))
        if area <= 0: continue
        for j in tri:
            for k in range(3): normals[j][k] += n[k]
        faces.append(tri)
        total += area
        weights.append(total)
    normals = [unit(n) if any(n) else (0., 1., 0.) for n in normals]
    rng = random.Random(20261114)
    points, directions = [], []
    for _ in range(count):
        tri = faces[bisect.bisect_left(weights, rng.random() * total)]
        u = math.sqrt(rng.random())
        v = rng.random()
        bary = (1-u, u*(1-v), u*v)
        points.append(tuple(sum(bary[j] * vertices[tri[j]][k] for j in range(3)) for k in range(3)))
        directions.append(unit(tuple(sum(bary[j] * normals[tri[j]][k] for j in range(3)) for k in range(3))))
    write_obj(ROOT / "data/bunny-points.obj", points, directions,
              f"Stanford bunny, {count} area-uniform surface samples with interpolated outward normals; seed 20261114\n# Source: {BUNNY_URL}\n# Source archive SHA256: {digest}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sphere-only", action="store_true")
    parser.add_argument("--bunny-count", type=int, default=2048)
    args = parser.parse_args()
    sphere()
    if not args.sphere_only: bunny(args.bunny_count)
